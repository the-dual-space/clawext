"""Tests for aliases, builtin name clashes, the skill marker and the testing helper."""

from __future__ import annotations

from pathlib import Path
from typing import Annotated

from clawext import Arg, Context, Opt, extension
from clawext.skill import generate_skill
from clawext.testing import invoke


def test_aliases_and_builtin_clash(plugin_env: None) -> None:
    """Aliases run the same command; an own ``status`` pushes the free one to ``ext-status``."""
    app = extension("a", "Aliases.")

    @app.command(aliases=["ls"])
    def list_all(ctx: Context) -> list[int]:
        """List."""
        return [1]

    @app.command
    def status(ctx: Context) -> str:
        """Own status."""
        return "mine"

    assert invoke(app, "--json", "ls").stdout.strip().replace("\n", "").replace(" ", "") == "[1]"
    assert invoke(app, "status").stdout.strip() == "mine"
    assert invoke(app, "ext-status", "--json").exit_code == 0
    assert "ls" not in invoke(app, "--help").stdout.split("Commands:")[1]


def test_skill_has_generated_marker(plugin_env: None) -> None:
    """The built-in skill says it is generated."""
    app = extension("m", "Marker.")
    assert "Generated by clawext" in generate_skill(app)


def test_usage_shows_optional_positional_and_short_flags(plugin_env: None) -> None:
    """The generated reference writes ``[name]`` for optional positionals and lists short flags."""
    app = extension("u", "Usage.")

    @app.command
    def index(
        ctx: Context,
        name: Annotated[str | None, Arg()] = None,
        vault: Annotated[str | None, Opt("-v")] = None,
    ) -> None:
        """Index."""

    text = generate_skill(app)
    assert "### `u index [name] [-v|--vault]`" in text
    assert "`-v`, `--vault` (str | None" in text


def test_skill_path_resolves_next_to_module(plugin_env: None, tmp_path: Path) -> None:
    """A relative ``skill=`` path is found relative to the declaring module (or above)."""
    app = extension("r", "Rel.", skill="tests/test_surface.py")
    assert app.skill_template is not None and app.skill_template.is_file()
